export type Localizer = (key: string, args?: Record<string, string | number>) => string;

export function localizer(language: string | undefined): Localizer {
  const table = (language ?? "en").toLowerCase().startsWith("nl") ? NL : EN;
  return (key, args) => {
    let text = table[key] ?? EN[key] ?? key;
    for (const [k, v] of Object.entries(args ?? {})) text = text.replace(`{${k}}`, String(v));
    return text;
  };
}

